export function getReviewsForWorker(workerId: string): Review[] {
  return REVIEWS.filter((r) => r.workerId === workerId).sort(
    (a, b) => +new Date(b.date) - +new Date(a.date)
  );
}

/** Rating distribution buckets (5 -> 1) for a worker's reviews. */
export function ratingDistribution(workerId: string): Record<number, number> {
  const dist: Record<number, number> = { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
  for (const r of REVIEWS.filter((x) => x.workerId === workerId)) {
    dist[r.rating] = (dist[r.rating] ?? 0) + 1;
  }
  return dist;
}
